#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────
#  سكريبت تشغيل كامل: k6 ← نتائج JSON ← تقرير PDF عربي
# ─────────────────────────────────────────────────────────────

set -e

BASE_URL="${BASE_URL:-https://your-platform.com}"
SUMMARY="summary.json"
REPORT="تقرير_الأداء.pdf"

echo "════════════════════════════════════════"
echo "  🚀 بدء اختبار الأداء"
echo "  🌐 المنصة: $BASE_URL"
echo "════════════════════════════════════════"

# ── 1. تثبيت المتطلبات ──────────────────────────────────────
echo ""
echo "📦 تثبيت متطلبات Python..."
pip install -q -r requirements.txt

# ── 2. تشغيل k6 ─────────────────────────────────────────────
echo ""
echo "⚡ تشغيل اختبار k6..."
k6 run --summary-export="$SUMMARY" --env BASE_URL="$BASE_URL" k6-test.js

# ── 3. توليد التقرير ─────────────────────────────────────────
echo ""
echo "📄 توليد تقرير PDF عربي..."
python generate_report.py "$SUMMARY" "$REPORT"

echo ""
echo "════════════════════════════════════════"
echo "  ✅ اكتمل — التقرير: $REPORT"
echo "════════════════════════════════════════"
